# CAM one-shot launcher (Windows PowerShell).
# Usage:
#   .\scripts\run_cam.ps1                # admin: prompted for email, password generated
#   .\scripts\run_cam.ps1 me@corp.in     # admin email given, password generated
#   .\scripts\run_cam.ps1 me@corp.in s3cret
#   .\scripts\run_cam.ps1 install        # install global launcher "camup.ps1" (~\bin)
# Admin email/password can also come from CAM_ADMIN_EMAIL / CAM_ADMIN_PASSWORD.
# Repo location defaults to the sibling of this script; override with CAM_HOME.

$ErrorActionPreference = "Stop"

function Write-Log([string]$m) { Write-Host "[CAM] $m" -ForegroundColor Green }
function Write-Warn2([string]$m) { Write-Host "[CAM] $m" -ForegroundColor Yellow }
function Die([string]$m) { Write-Host "[CAM] $m" -ForegroundColor Red; exit 1 }

if ($env:CAM_HOME) { $RepoRoot = $env:CAM_HOME } else { $RepoRoot = Split-Path -Parent $PSScriptRoot }
Set-Location $RepoRoot
if (-not (Test-Path (Join-Path $RepoRoot "docker-compose.yml"))) {
    Die "CAM repo not found at $RepoRoot - set CAM_HOME=C:\path\to\cam"
}

# --- install subcommand -------------------------------------------------------
if ($args.Count -gt 0 -and $args[0] -eq "install") {
    $GlobalBin = Join-Path $env:USERPROFILE "bin"
    New-Item -ItemType Directory -Force $GlobalBin | Out-Null
    $Launcher = Join-Path $GlobalBin "camup.ps1"
    # Generate a launcher that PINS the repo it was installed from. A plain copy
    # of this script made the installed file resolve its repo from its own
    # location, i.e. ~\bin -> outside the repo (R38).
    $LauncherBody = @"
# CAM launcher - generated by scripts/run_cam.ps1 install.
# Pins the repo this was installed from; re-run install after the repo moves.
`$env:CAM_HOME = '$RepoRoot'
& '$RepoRoot\scripts\run_cam.ps1' @args
"@
    Set-Content -Path $Launcher -Value $LauncherBody -Encoding UTF8
    Write-Log "Installed: $Launcher (launcher pinned to $RepoRoot; re-run install if the repo moves)"
    $userPath = [Environment]::GetEnvironmentVariable("Path", "User")
    if ($userPath -notlike "*$GlobalBin*") {
        Write-Warn2 "$GlobalBin is not on PATH - add it for global runs:"
        [Environment]::SetEnvironmentVariable("Path", "$userPath;$GlobalBin", "User")
        Write-Log "PATH updated (User) - restart the terminal once."
    }
    Write-Log "If scripts are blocked by execution policy: Set-ExecutionPolicy -Scope CurrentUser RemoteSigned"
    exit 0
}

Write-Log "Directory: $RepoRoot"

docker info *> $null
if ($LASTEXITCODE -ne 0) { Die "Docker is not running. Install/start it first: https://docs.docker.com/desktop/setup/install/windows-install/" }

# --- Secrets (kept in gitignored .env so they survive restarts) ---------------
if (-not (Test-Path .env)) { New-Item -ItemType File .env | Out-Null }
(Get-Item .env).Attributes = "Hidden"  # best-effort chmod 600 equivalent on Windows

function Get-EnvValue([string]$key) {
    $line = Get-Content .env | Where-Object { $_ -match "^$key=" } | Select-Object -First 1
    if ($line) { $line.Substring($key.Length + 1) } else { "" }
}
function Set-EnvValue([string]$key, [string]$value) {
    if (Get-Content .env | Where-Object { $_ -match "^$key=" }) {
        $tmp = Get-Content .env | ForEach-Object { if ($_ -match "^$key=") { "$key=$value" } else { $_ } }
        Set-Content .env $tmp
    } else { Add-Content .env "$key=$value" }
}

function New-KeyB64 {
    $b = New-Object byte[] 32
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b)
    [Convert]::ToBase64String($b)
}

if (-not $env:CAM_ENCRYPTION_KEYS) {
    if (-not (Get-EnvValue "CAM_ENCRYPTION_KEYS")) { Set-EnvValue "CAM_ENCRYPTION_KEYS" "v1:$(New-KeyB64)" }
}
if (-not (Get-EnvValue "CAM_ENCRYPTION_KEY_CURRENT")) { Set-EnvValue "CAM_ENCRYPTION_KEY_CURRENT" "v1" }
if (-not (Get-EnvValue "CAM_SESSION_SECRET")) { Set-EnvValue "CAM_SESSION_SECRET" (New-KeyB64) }

# --- Build & start the stack ---------------------------------------------------
Write-Log "Building and starting the app + database container..."
docker compose up -d --build

$PortLine = docker compose port app 8000 2>$null | Select-Object -First 1
if ($PortLine -match ":(\d+)\s*$") { $Port = $Matches[1] } else { $Port = "8001" }
$Base = "http://localhost:$Port"

Write-Log "Waiting for CAM to become healthy (first build can take a few minutes)..."
$Healthy = $false
foreach ($i in 1..120) {
    # Ask the container itself (same as the compose healthcheck)
    docker compose exec -T app python -c "import urllib.request; urllib.request.urlopen('http://127.0.0.1:8000/api/health')" *> $null
    if ($LASTEXITCODE -eq 0) { $Healthy = $true; break }
    Start-Sleep -Seconds 5
}
if (-not $Healthy) { docker compose logs --tail 80 app; Die "CAM did not become healthy in time (see app logs above)." }
Write-Log "CAM is up."

# --- Admin bootstrap (only if there is no active admin yet) -------------------
$AdminEmail = $env:CAM_ADMIN_EMAIL; if (-not $AdminEmail -and $args.Count -gt 0) { $AdminEmail = $args[0] }
$AdminPassword = $env:CAM_ADMIN_PASSWORD; if (-not $AdminPassword -and $args.Count -gt 1) { $AdminPassword = $args[1] }

$AdminCount = 0
try {
    $out = docker compose exec -T db psql -U cam -d cam -tAc "SELECT COUNT(*) FROM users WHERE role='admin' AND status='active';" 2>$null
    $AdminCount = [int]($out | Select-Object -First 1)
} catch { $AdminCount = 0 }

if ($AdminCount -gt 0) {
    Write-Log "An admin already exists - skipping create-admin."
} else {
    if (-not $AdminEmail) { $AdminEmail = Read-Host "Admin email" }
    if (-not $AdminPassword) {
        $chars = "abcdefghjkmnpqrstuvwxyzABCDEFGHJKMNPQRSTUVWXYZ23456789".ToCharArray()
        $AdminPassword = -join (1..18 | ForEach-Object { $chars[(Get-Random -Maximum $chars.Length)] })
        $Generated = $true
    }
    # Host env vars do NOT propagate into `docker compose exec`; pass them with
    # -e so the container's create-admin sees them (R38).
    docker compose exec -T -e "CAM_ADMIN_EMAIL=$AdminEmail" -e "CAM_ADMIN_PASSWORD=$AdminPassword" app sh -c 'uv run --no-sync cam create-admin --email "$CAM_ADMIN_EMAIL" --password "$CAM_ADMIN_PASSWORD"'
    if ($LASTEXITCODE -ne 0) { Die "Creating the admin failed (see output above)." }
    if ($Generated) { Write-Host "[CAM] Admin password (save it now - shown once): $AdminPassword" -ForegroundColor Green }
}

# --- Summary -------------------------------------------------------------------
Write-Host ""
Write-Host "=== CAM is running ===" -ForegroundColor Green
Write-Host "Dashboard:   $Base"
Write-Host "API health:  $Base/api/health"
Write-Host "MCP URL:     $Base/mcp"
Write-Host ""
Write-Host "Claude Code: claude mcp add --transport http cam $Base/mcp --header `"Authorization: Bearer <token>`""
Write-Host "Cursor/Codex, other commands, docs: docs/onboarding.md"
Write-Host "Login with the admin account created above (or the existing one)."
Write-Host "Stop: docker compose down  (keeps data)  |  Stop+wipe: docker compose down -v"
